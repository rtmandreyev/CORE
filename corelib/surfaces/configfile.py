"""Starship and Fastfetch: one configuration file CORE writes as a copy.

The installed file is a plain copy of the build output, so deleting or moving
the CORE repository never breaks a prompt. A previous symlink (including one
an older CORE created into the repository) is captured and restored exactly.
"""

from __future__ import annotations

from pathlib import Path

from corelib import effects, fileops
from corelib.surfaces.base import ACTIVE, NA, READY, REPAIRABLE, Integration, Status, Surface

MARKER = "Generated by CORE"


class ConfigFile(Surface):
    tool = ""
    build_key = ""
    repairable = True

    def config(self, paths) -> Path:
        raise NotImplementedError

    def available(self, paths):
        if self.config(paths).exists() or self.config(paths).is_symlink():
            return (True, "")
        if effects.current().which(self.tool):
            return (True, "")
        return (False, f"{self.label} is not installed")

    def wanted(self, ctx, theme) -> str:
        return ctx.built(theme).path(self.build_key).read_text()

    def status(self, ctx, theme):
        installed, reason = self.available(ctx.paths)
        if not installed:
            return Status(NA, reason)
        if not self.verify(ctx, theme):
            return Status(ACTIVE, theme.short_name)
        path = self.config(ctx.paths)
        current = "a symlink" if path.is_symlink() else ("not configured" if not path.exists() else "another configuration")
        return Status(READY, f"currently {current}")

    def capture(self, ctx, theme):
        path = self.config(ctx.paths)
        return {"path": str(path), "state": fileops.snapshot(path)}

    def apply(self, ctx, theme, captured):
        path = self.config(ctx.paths)
        if path.is_symlink():
            path.unlink()
        if fileops.read_text(path) == self.wanted(ctx, theme):
            return [f"{path.name} already current"]
        fileops.write_text(path, self.wanted(ctx, theme))
        return [f"wrote {path}"]

    def ensure(self, ctx, theme):
        """Repair: rewrite a stale CORE file or replace a broken link."""

        if self.integration(ctx, theme).state != REPAIRABLE:
            return []
        path = self.config(ctx.paths)
        if path.is_symlink():
            path.unlink()
        fileops.write_text(path, self.wanted(ctx, theme))
        return [f"rewrote {path}"]

    def verify(self, ctx, theme):
        path = self.config(ctx.paths)
        if path.is_symlink() or fileops.read_text(path) != self.wanted(ctx, theme):
            return [f"{path} does not contain the {theme.short_name} configuration"]
        return []

    def restore(self, ctx, captured):
        result = fileops.restore_snapshot(Path(captured["path"]), captured["state"])
        return [f"{Path(captured['path']).name} {result}"]

    def integration(self, ctx, theme):
        installed, reason = self.available(ctx.paths)
        if not installed:
            return Integration(NA, reason=reason)
        path = self.config(ctx.paths)
        text = fileops.read_text(path)
        facts = [("config", str(path)), ("form", "symlink" if path.is_symlink() else ("file" if text is not None else "missing"))]
        owned = text is not None and MARKER in text and theme is not None and f"{theme.name} for" in text
        if theme is not None and owned and text != self.wanted(ctx, theme):
            facts.append(("content", "CORE file is out of date"))
            return Integration(REPAIRABLE, facts, [f"Rewrite {path} from the current {theme.short_name} build"],
                               reason="CORE configuration is out of date")
        if theme is not None and not owned and path.is_symlink() and not path.exists():
            facts.append(("content", "broken symlink"))
            return Integration(REPAIRABLE, facts, [f"Replace the broken link at {path} with the {theme.short_name} configuration"],
                               reason="the installed configuration is a broken symlink")
        facts.append(("content", "current CORE configuration" if owned else "not managed by CORE"))
        return Integration(ACTIVE if owned else READY, facts)


class Starship(ConfigFile):
    key = "starship"
    label = "Starship"
    tool = "starship"
    build_key = "starship"

    def config(self, paths):
        return paths.starship_config


class Fastfetch(ConfigFile):
    key = "fastfetch"
    label = "Fastfetch"
    tool = "fastfetch"
    build_key = "fastfetch"

    def config(self, paths):
        return paths.fastfetch_config
